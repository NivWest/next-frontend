#!/usr/bin/env node
// Contract tooling for the backend OpenAPI spec (story NW-07). The backend's api/openapi.yaml is the source of
// truth; this repo keeps a vendored copy in api/openapi.yaml and generates src/lib/api/schema.d.ts from it.
//
//   npm run api:sync   copy $BACKEND_DIR/api/openapi.yaml (default ../backend) over the vendored copy
//   npm run api:gen    regenerate src/lib/api/schema.d.ts from the vendored copy
//   npm run api:check  fail when schema.d.ts is not what api:gen would write (CI); warn when the vendored
//                      copy differs from a backend checkout next to this repo
import { copyFile, readFile, writeFile, mkdir } from 'node:fs/promises';
import { existsSync } from 'node:fs';
import { dirname, resolve } from 'node:path';
import { fileURLToPath } from 'node:url';
import openapiTS, { astToString } from 'openapi-typescript';

const root = resolve(dirname(fileURLToPath(import.meta.url)), '..');
const vendored = resolve(root, 'api/openapi.yaml');
const generated = resolve(root, 'src/lib/api/schema.d.ts');
const backendSpec = resolve(process.env.BACKEND_DIR ?? resolve(root, '../backend'), 'api/openapi.yaml');

const HEADER = `/**
 * GENERATED by \`npm run api:gen\` from api/openapi.yaml (a vendored copy of the backend's api/openapi.yaml).
 * Do not edit by hand: change the backend contract, then run \`npm run api:sync && npm run api:gen\`.
 */

`;

async function render() {
  const ast = await openapiTS(new URL(`file://${vendored}`));
  return HEADER + astToString(ast);
}

async function sync() {
  if (!existsSync(backendSpec)) {
    throw new Error(`No backend spec at ${backendSpec}. Set BACKEND_DIR to the backend checkout.`);
  }
  await mkdir(dirname(vendored), { recursive: true });
  await copyFile(backendSpec, vendored);
  console.log(`api:sync: copied ${backendSpec} -> api/openapi.yaml`);
}

async function gen() {
  await mkdir(dirname(generated), { recursive: true });
  await writeFile(generated, await render());
  console.log('api:gen: wrote src/lib/api/schema.d.ts');
}

async function check() {
  let ok = true;
  if (existsSync(backendSpec)) {
    const [mine, theirs] = await Promise.all([readFile(vendored, 'utf8'), readFile(backendSpec, 'utf8')]);
    if (mine !== theirs) {
      console.warn(`api:check: warning: api/openapi.yaml differs from ${backendSpec}; run \`npm run api:sync\` if the backend is on the matching branch.`);
    }
  }
  const want = await render();
  const have = existsSync(generated) ? await readFile(generated, 'utf8') : '';
  if (want !== have) {
    console.error('api:check: src/lib/api/schema.d.ts is out of date with api/openapi.yaml; run `npm run api:gen` and commit it.');
    ok = false;
  }
  if (ok) console.log('api:check: src/lib/api/schema.d.ts matches api/openapi.yaml');
  return ok;
}

const commands = { sync, gen, check };
const command = commands[process.argv[2]];
if (!command) {
  console.error(`usage: node scripts/api-contract.mjs <${Object.keys(commands).join('|')}>`);
  process.exit(2);
}
try {
  const result = await command();
  if (result === false) process.exit(1);
} catch (err) {
  console.error(err instanceof Error ? err.message : err);
  process.exit(1);
}
